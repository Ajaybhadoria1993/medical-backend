const COLLEGE_SEARCH_LIMIT = 25;

// Initials of the name before the city, minus "of"/"and": "All India Institute of Medical Sciences" → "aiims".
const initials = (name: string) =>
  name
    .split(',')[0]
    .toLowerCase()
    .split(/[\s-]+/)
    .filter((w) => w && !['of', 'and', '&'].includes(w))
    .map((w) => w[0])
    .join('');

const COLLEGES = COLLEGE_ROWS.map(([name, state, stream]) => ({
  name,
  state,
  stream,
  key: name.toLowerCase(),
  initials: initials(name),
}));
const COLLEGE_BY_KEY = new Map(COLLEGES.map((c) => [c.key, c.name]));

/** Official spelling of a listed college; anything else is kept as typed. */
export const canonicalCollege = (value: string) => {
  const tidy = value.trim().replace(/\s+/g, ' ');
  return COLLEGE_BY_KEY.get(tidy.toLowerCase()) ?? tidy;
};

// Lower is better: exact → starts with → a word starts with → contains → initials → state → every word.
const matchTier = (college: (typeof COLLEGES)[number], q: string) => {
  const { key, initials: abbr, state } = college;
  const stateKey = state.toLowerCase();
  if (key === q) return 0;
  if (key.startsWith(q)) return 1;
  if (key.includes(` ${q}`)) return 2;
  if (key.includes(q)) return 3;
  if (q.length >= 3 && !q.includes(' ') && abbr.startsWith(q)) return 4;
  if (stateKey.includes(q)) return 5;
  // "aiims delhi": each word is found in the name, the initials or the state.
  const words = q.split(' ');
  const wordHit = (w: string) =>
    key.includes(w) ||
    stateKey.includes(w) ||
    (w.length >= 3 && abbr.startsWith(w));
  return words.length > 1 && words.every(wordHit) ? 6 : -1;
};

/** Colleges whose name, initials or state match `q`, best match first; `stream` ranks its colleges higher. */
export function searchColleges(q: string, stream?: string) {
  const query = q.trim().replace(/\s+/g, ' ').toLowerCase();
  return COLLEGES.map((c) => ({ c, tier: matchTier(c, query) }))
    .filter(({ tier }) => tier >= 0)
    .sort(
      (a, b) =>
        a.tier - b.tier ||
        Number(b.c.stream === stream) - Number(a.c.stream === stream) ||
        a.c.name.length - b.c.name.length ||
        a.c.name.localeCompare(b.c.name)
    )
    .slice(0, COLLEGE_SEARCH_LIMIT)
    .map(({ c }) => ({ name: c.name, state: c.state, stream: c.stream }));
}
